#!/usr/bin/env python3
"""Deterministic test data for the hand-written test programs.

  tools/make_testdata.py [--check]

Writes tests/data/<schema>/{small,medium,large}_<i>.json for every schema:
  example  minivm-takehome/examples/schema.json, literals from examples/programs + tests/cases/**
  <name>   tests/schemas/<name>/schema.json, literals from tests/schemas/<name>/programs/*.mini
Each file is generated by evaluator/datagen.py from a fixed seed and validated with
`bin/minivm --schema`. Output is byte-for-byte reproducible (sorted literal pools,
fixed seeds, sorted JSON keys are NOT used: datagen's table order is kept).
--check regenerates into memory and reports any file that differs from disk.
"""
import glob
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)

from evaluator import datagen, vm  # noqa: E402

EX = os.path.join(REPO, "minivm-takehome", "examples")
OUT = os.path.join(REPO, "tests", "data")
# size -> number of datasets; seeds are base + i
PLAN = (("small", 3, 1000), ("medium", 3, 2000), ("large", 2, 3000))


def schemas():
    """-> [(name, schema_path, [program paths])]"""
    progs = sorted(glob.glob(os.path.join(EX, "programs", "*.mini")))
    progs += sorted(glob.glob(os.path.join(REPO, "tests", "cases", "**", "*.mini"), recursive=True))
    out = [("example", os.path.join(EX, "schema.json"), progs)]
    for d in sorted(glob.glob(os.path.join(REPO, "tests", "schemas", "*", ""))):
        sp = os.path.join(d, "schema.json")
        if os.path.exists(sp):
            out.append((os.path.basename(os.path.dirname(d)), sp,
                        sorted(glob.glob(os.path.join(d, "programs", "*.mini")))))
    return out


def render(schema, size, seed, lits):
    return json.dumps(datagen.generate(schema, size, seed, lits), ensure_ascii=False) + "\n"


def main(argv):
    check = "--check" in argv
    bad = 0
    for name, sp, progs in schemas():
        schema = json.load(open(sp, encoding="utf-8"))
        lits = datagen.harvest(open(p, encoding="utf-8").read() for p in progs)
        d = os.path.join(OUT, name)
        os.makedirs(d, exist_ok=True)
        for size, n, base in PLAN:
            for i in range(n):
                text = render(schema, size, base + i, lits)
                path = os.path.join(d, f"{size}_{i}.json")
                if check:
                    same = os.path.exists(path) and open(path, encoding="utf-8").read() == text
                    if not same:
                        print(f"DIFFERS {os.path.relpath(path, REPO)}")
                        bad += 1
                    continue
                fd, tmp = tempfile.mkstemp(dir=d, suffix=".json")
                with os.fdopen(fd, "w", encoding="utf-8") as f:
                    f.write(text)
                s, err = vm.schema_of(tmp)
                if s is None:
                    os.unlink(tmp)
                    print(f"INVALID {name} {size} seed {base + i}: {err}")
                    bad += 1
                    continue
                os.replace(tmp, path)
                rows = sum(t["stats"]["rows"] for t in s.values())
                print(f"wrote {os.path.relpath(path, REPO)}  ({rows} rows)")
    if check and not bad:
        print("all test data up to date")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
